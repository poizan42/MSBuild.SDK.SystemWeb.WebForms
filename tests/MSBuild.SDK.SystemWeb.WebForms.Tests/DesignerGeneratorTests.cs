    private const string PageDirective = "<%@ Page Language=\"C#\" AutoEventWireup=\"true\" CodeBehind=\"Default.aspx.cs\" Inherits=\"WebApp._Default\" %>\r\n";
    private const string DefaultCodeBehind = "namespace WebApp { public partial class _Default : System.Web.UI.Page { } }";
    private const string DefaultHint = "Default.aspx.designer.g.cs";

    private const string WebControls = "global::System.Web.UI.WebControls.";
