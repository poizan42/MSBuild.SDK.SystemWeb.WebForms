    [NetFx48Fact]
    public void Basic_page_generates_fields_in_markup_order_with_vs_layout()
    {
        var result = Page(
            "<html><body><form id=\"form1\" runat=\"server\">" +
            "<asp:Label ID=\"lblName\" runat=\"server\" /><asp:TextBox ID=\"txtName\" runat=\"server\"></asp:TextBox>" +
            "</form></body></html>").Run();

        DesignerAssert.NoDiagnostics(result);
        var source = result.GetSource(DefaultHint);
        Assert.Contains("// <auto-generated>", source);
        Assert.Contains("namespace WebApp {", source);
        Assert.Contains("partial class _Default {", source);
        DesignerAssert.HasField(source, HtmlControls + "HtmlForm", "form1");
        DesignerAssert.HasField(source, WebControls + "Label", "lblName");
        DesignerAssert.HasField(source, WebControls + "TextBox", "txtName");
        Assert.True(source.IndexOf("form1;", StringComparison.Ordinal) < source.IndexOf("lblName;", StringComparison.Ordinal));
        Assert.True(source.IndexOf("lblName;", StringComparison.Ordinal) < source.IndexOf("txtName;", StringComparison.Ordinal));
        Assert.Contains("/// To modify move field declaration from designer file to code-behind file.", source);
        DesignerAssert.Compiles(result);
    }

